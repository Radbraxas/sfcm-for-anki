// Generates TypeScript types from the engine's protocol schema (roadmap A07).
// Usage: node scripts/gen-types.mjs <schema.json> <out.ts>
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const [schemaPath, outPath] = process.argv.slice(2);
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const defs = schema.$defs;

// Pydantic titles every property ("Front", "Notetype"); the compiler would turn each
// into a named alias. Keep titles only on the definitions themselves.
const stripTitles = (node, keep) => {
  if (Array.isArray(node)) {
    for (const item of node) stripTitles(item, false);
  } else if (node && typeof node === "object") {
    // biome-ignore lint/performance/noDelete: build script, removing a key is the point
    if (!keep) delete node.title;
    for (const value of Object.values(node)) stripTitles(value, false);
  }
};
for (const def of Object.values(defs)) stripTitles(def, true);

// Compile every definition by giving the compiler a root that references them all.
const root = {
  title: "ProtocolRoot",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(
    Object.keys(defs).map((name) => [name, { $ref: `#/$defs/${name}` }]),
  ),
  $defs: defs,
};
let body = await compile(root, "ProtocolRoot", {
  bannerComment: "",
  additionalProperties: false,
  declareExternallyReferenced: true,
  strictIndexSignatures: true,
  format: false,
});
// The synthetic root is not part of the protocol.
body = body.replace(/export interface ProtocolRoot \{[\s\S]*?\n\}\n/, "");

const methodLines = (table) =>
  Object.entries(table)
    .map(
      ([name, { params, result }]) =>
        `  ${JSON.stringify(name)}: { params: ${params}; result: ${result} };`,
    )
    .join("\n");
const notificationLines = Object.entries(schema["x-notifications"])
  .map(([name, params]) => `  ${JSON.stringify(name)}: ${params};`)
  .join("\n");

const out = `// GENERATED by ui/scripts/gen-types.mjs from engine/schema/protocol.schema.json.
// Do not edit by hand: change engine/src/sfcm_engine/protocol.py and run \`just gen\`.
/* eslint-disable */

export const PROTOCOL_VERSION = ${schema["x-protocol-version"]};

${body.trim()}

/** UI -> engine requests. */
export interface MethodMap {
${methodLines(schema["x-methods"])}
}

/** Engine -> shell requests (handled in Rust, listed for reference). */
export interface ShellMethodMap {
${methodLines(schema["x-shell-methods"])}
}

/** Engine -> UI notifications. */
export interface NotificationMap {
${notificationLines}
}

export type Method = keyof MethodMap;
`;
await writeFile(outPath, out);
console.log(`wrote ${outPath}`);
